import json
import logging
import os
import subprocess
import sys
import time
from typing import Any, Dict, List, Set

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] [p2p.sync] %(message)s"
)
logger = logging.getLogger("ccc.p2p.router.sync")

UPSTREAM_CONF_PATH = os.getenv("NGINX_UPSTREAM_CONF", "/etc/nginx/conf.d/peer-upstreams.conf")
REDIS_HOST = os.getenv("REDIS_HOST", "127.0.0.1")
REDIS_PORT = int(os.getenv("REDIS_PORT", 6379))
